#!/usr/bin/env node
// Keep local distributables in one place; unpacked apps remain in the build output.
import { createHash } from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import process from 'node:process'

const projectRoot = path.resolve(import.meta.dirname, '..')
const outputArg = process.argv.find((item) => item.startsWith('--output='))?.slice('--output='.length) || 'release'
const platform = process.argv.find((item) => item.startsWith('--platform='))?.slice('--platform='.length) || 'all'
if (!['mac', 'win', 'android', 'all'].includes(platform)) throw new Error(`未知平台：${platform}`)
const output = path.resolve(projectRoot, outputArg)
const current = path.join(projectRoot, '安装包', '当前')
const history = path.join(projectRoot, '安装包', '历史版本')
const version = JSON.parse(fs.readFileSync(path.join(projectRoot, 'package.json'), 'utf8')).version
const escapedVersion = version.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
const selected = (name) => {
  if (['mac', 'all'].includes(platform) && new RegExp(`^ZSense-${escapedVersion}-mac-(arm64|x64)\\.(dmg|zip)(\\.blockmap)?$`).test(name)) return true
  if (['win', 'all'].includes(platform) && new RegExp(`^ZSense-${escapedVersion}-win-x64\\.exe(\\.blockmap)?$`).test(name)) return true
  return (['mac', 'all'].includes(platform) && name === 'latest-mac.yml') || (['win', 'all'].includes(platform) && name === 'latest.yml')
}
const sha256 = async (file) => {
  const hash = createHash('sha256')
  for await (const chunk of fs.createReadStream(file)) hash.update(chunk)
  return hash.digest('hex')
}
const historicalName = (file) => {
  const ext = path.extname(file)
  const base = file.slice(0, -ext.length)
  const stamp = new Date(fs.statSync(path.join(current, file)).mtimeMs).toISOString().replace(/[-:]/g, '').replace('T', '-').slice(0, 15)
  let candidate = `${base}-${stamp}${ext}`
  let index = 2
  while (fs.existsSync(path.join(history, candidate))) candidate = `${base}-${stamp}-${index++}${ext}`
  return candidate
}

if (!fs.existsSync(output)) process.exit(0)
fs.mkdirSync(current, { recursive: true })
fs.mkdirSync(history, { recursive: true })
async function moveArtifact(source, name) {
  if (!fs.lstatSync(source).isFile()) return
  const target = path.join(current, name)
  if (fs.existsSync(target)) {
    if (fs.statSync(source).size === fs.statSync(target).size && await sha256(source) === await sha256(target)) {
      fs.unlinkSync(source) // exact duplicate generated by a repeated local build
      console.log(`相同安装产物已存在：${name}`)
      return
    }
    fs.renameSync(target, path.join(history, historicalName(name)))
  }
  fs.renameSync(source, target)
  console.log(`安装产物已归档：${path.relative(projectRoot, target)}`)
}
for (const name of fs.readdirSync(output).filter(selected).sort()) await moveArtifact(path.join(output, name), name)
if (platform === 'android' || platform === 'all') {
  const metadataPath = path.join(output, 'output-metadata.json')
  if (fs.existsSync(metadataPath)) {
    const metadata = JSON.parse(fs.readFileSync(metadataPath, 'utf8'))
    if (metadata.variantName === 'release') for (const element of metadata.elements || []) {
      const sourceName = path.basename(element.outputFile || '')
      if (!/^app-release\.apk$/.test(sourceName) || !/^\d+\.\d+\.\d+$/.test(element.versionName || '')) continue
      const source = path.join(output, sourceName)
      if (fs.existsSync(source)) await moveArtifact(source, `ZSense-${element.versionName}-android13-release.apk`)
    }
  }
}
